/* 
This program calculates the sum of two integers.
It stores the sum in a variable and displays it using cout.
*/

#include <iostream>
using namespace std;

int main() {
    // Initialize two integer variables
    int a = 10, b = 20;

    // Calculate sum of a and b
    int sum = a + b;

    // Display the sum
    cout << "Sum = " << sum;

    // End program
    return 0;
}
