/* 
This program prints numbers from 1 to 10 using a for-loop.
It demonstrates simple iteration in C++ and output using cout.
*/

#include <iostream>
using namespace std;

int main() {
// Loop from 1 to 10
    for(int i = 1; i <= 10; i++) {
// Print current number
    cout << i << " ";
    }

// End program
    return 0;
}
