/* 
This program demonstrates basic addition of two integers in C++.
It calculates the sum and displays the result using cout.
*/

#include <iostream>
using namespace std;

int main() {
// Initialize two integer variables
    int a = 10, b = 20;

// Calculate sum of a and b
    int sum = a + b;

// Display the sum
    cout << "Sum = " << sum;

// End program
    return 0;
}
