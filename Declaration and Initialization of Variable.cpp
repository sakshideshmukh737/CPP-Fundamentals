/* 
This program demonstrates different data types in C++: int, float, and char.
It stores values in variables and displays them using cout.
*/

#include <iostream>
using namespace std;

int main() {
    int age = 18;
    float height = 5.6;
    char grade = 'A';

    cout << age << endl;
    cout << height << endl;
    cout << grade << endl;

    return 0;
}
