/* 
This program demonstrates relational operators in C++.
It compares two integers and displays the results of the comparisons.
*/

#include <iostream>
using namespace std;

int main() {
    // Initialize two integer variables
    int a = 5, b = 10;

    // Check if a is greater than b
    cout << (a > b) << endl;

    // Check if a is less than b
    cout << (a < b) << endl;

    // Check if a is equal to b
    cout << (a == b) << endl;

    // Check if a is not equal to b
    cout << (a != b) << endl;

    // End program
    return 0;
}
